import os
import sys
import subprocess
try:
    from reportlab.lib.pagesizes import A4
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors
    from reportlab.lib.units import inch
    from reportlab.pdfgen import canvas
except ImportError:
    print("ReportLab not found. Please install using: pip install reportlab")
    sys.exit(1)

# Custom Canvas for "Page X of Y"
class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        canvas.Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor('#64748B'))
        text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 0.5 * inch, 0.5 * inch, text)
        self.drawString(0.5 * inch, A4[1] - 0.4 * inch, "AURA_FACE Developer Bible & Architecture Manual")
        self.restoreState()

def generate_manual():
    pdf_filename = "AURA_FACE_Developer_Bible_and_Architecture_Manual.pdf"
    doc = SimpleDocTemplate(
        pdf_filename,
        pagesize=A4,
        rightMargin=0.5*inch,
        leftMargin=0.5*inch,
        topMargin=0.6*inch,
        bottomMargin=0.8*inch
    )

    styles = getSampleStyleSheet()
    
    # Custom Themes
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Title'],
        fontName='Helvetica-Bold',
        fontSize=28,
        spaceAfter=25,
        textColor=colors.HexColor('#0F172A')
    )
    
    h1_style = ParagraphStyle(
        'H1Style',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=18,
        spaceBefore=20,
        spaceAfter=12,
        textColor=colors.HexColor('#0284C7')
    )
    
    h2_style = ParagraphStyle(
        'H2Style',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        spaceBefore=15,
        spaceAfter=8,
        textColor=colors.HexColor('#334155')
    )
    
    body_style = ParagraphStyle(
        'BodyStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        spaceBefore=6,
        spaceAfter=6,
        leading=14
    )
    
    code_style = ParagraphStyle(
        'CodeStyle',
        parent=styles['Code'],
        fontName='Courier',
        fontSize=8,
        leading=10,
        spaceBefore=8,
        spaceAfter=8,
        textColor=colors.HexColor('#0F172A'),
        backColor=colors.HexColor('#F1F5F9'),
        borderPadding=6
    )

    story = []

    # 1. Cover Page & Architecture Foundations
    story.append(Paragraph("AURA-FACE: Developer Bible & Architecture Manual", title_style))
    story.append(Spacer(1, 0.5*inch))
    
    story.append(Paragraph("1. Cover Page & Architecture Foundations", h1_style))
    story.append(Paragraph("This exhaustive manual details the technical foundations, mathematical limits, and file-by-file logic of the AURA-FACE system.", body_style))
    
    story.append(Paragraph("Dependency Matrix", h2_style))
    story.append(Paragraph("Python 3.10+, PyTorch (MobileNetV2), OpenCV (YuNet), FAISS (IndexFlatL2 wrapped in IndexIDMap2), CustomTkinter, and SQLite3.", body_style))
    
    # 2. Mathematical Derivations & Thresholds
    story.append(Paragraph("2. Mathematical Derivations & Thresholds", h1_style))
    

        
    story.append(Paragraph("High-dimensional Vector Space & L2 Normalization", h2_style))
    story.append(Paragraph(
        "Vectors generated by the PyTorch embedder are 128-dimensional. These are strictly L2-normalized so they map onto a unit hypersphere. "
        "Because vectors are unit length, the Squared Euclidean Distance used by FAISS mathematically directly maps to Cosine Similarity: "
        "L2_Sq = 2 - 2*cos(theta).", body_style))
        
    story.append(Paragraph("Dual-Threshold Gating", h2_style))
    story.append(Paragraph(
        "Strict Duplicate Blocking: Distance 0.15 (High similarity required to block true duplicates but allow lookalikes).<br/>"
        "Attendance Kiosk Match: Distance 0.55 (Standard tolerance accommodating lighting/expression variations).", body_style))
        
    story.append(PageBreak())

    # 3. Line-by-Line Code Breakdown
    story.append(Paragraph("3. Module-by-Module Code Breakdown", h1_style))
    
    target_files = ['face_engine.py', 'liveness_detector.py', 'vector_index.py', 'db_manager.py', 'app.py', 'evaluate_accuracy.py', 'resequence_uids.py']
    
    for filename in target_files:
        if os.path.exists(filename):
            story.append(Paragraph(f"Module: {filename}", h2_style))
            try:
                with open(filename, 'r', encoding='utf-8') as f:
                    lines = f.readlines()
                    
                snippet_text = ""
                for line in lines:
                    line_clean = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                    snippet_text += line_clean
                    if len(snippet_text) > 4000: # chunking long files
                        story.append(KeepTogether([Paragraph(snippet_text.replace(chr(10), '<br/>'), code_style)]))
                        snippet_text = ""
                
                if snippet_text:
                    story.append(KeepTogether([Paragraph(snippet_text.replace(chr(10), '<br/>'), code_style)]))
                    
            except Exception as e:
                story.append(Paragraph(f"Error reading {filename}: {e}", body_style))
        else:
            story.append(Paragraph(f"Module: {filename} (File not found)", h2_style))
            
    # 4. Database Schemas & FAISS Sync
    story.append(PageBreak())
    story.append(Paragraph("4. Database Schemas & FAISS Synchronization", h1_style))
    story.append(Paragraph("Users Table: id (PK), user_code (UNIQUE), name, registered_date. Attendance Table tracks unique punches per day.", body_style))
    story.append(Paragraph("ID Resequencing logic maps fragmented SQLite IDs sequentially and reconstructs the FAISS index to ensure harmony.", body_style))

    # 5. Testing, Verification, and Troubleshooting Matrix
    story.append(Paragraph("5. Testing, Verification, and Troubleshooting Matrix", h1_style))
    
    trouble_data = [
        ["Symptom", "Root Cause", "Resolution"],
        ["High False Rejection Rate (FRR)", "Kiosk threshold too low (e.g. 0.20)", "Revert Attendance threshold to 0.55."],
        ["Duplicate Prevention Blocking Friends", "Duplicate check threshold too high", "Lower duplicate threshold to 0.15."],
        ["OpenCV DNN Warnings spamming console", "YuNet ONNX backend verbosity", "Use cv2.utils.logging.setLogLevel(cv2.utils.logging.LOG_LEVEL_ERROR)."]
    ]
    
    t2_style = TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0284C7')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#F1F5F9')),
        ('GRID', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
        ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 1), (-1, -1), 9),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ])
    
    # Wrap table data in Paragraphs to prevent clipping
    for row_idx, row in enumerate(trouble_data):
        if row_idx == 0: continue
        for col_idx, cell in enumerate(row):
            trouble_data[row_idx][col_idx] = Paragraph(cell, body_style)
            
    t2_wrapped = Table(trouble_data, colWidths=[2.0*inch, 2.5*inch, 2.5*inch])
    t2_wrapped.setStyle(t2_style)
    
    story.append(t2_wrapped)

    # Build the document using the custom NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    
    # Trigger OS to open explorer and highlight the file
    pdf_path = os.path.abspath(pdf_filename)
    print(f"Manual successfully generated at: {pdf_path}")
    
    if sys.platform == "win32":
        subprocess.run(["explorer", "/select,", pdf_path])

if __name__ == '__main__':
    generate_manual()
